import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';

const url = process.env.PIPELINE_STATUS_TEST_URL;
const root = process.env.PIPELINE_STATUS_TEST_ROOT;
test('opportunity decisions persist only after confirmation, with disposable data', { skip: !url || !root, timeout: 90000 }, async t => {
  const origin = new URL(url);
  assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(origin.hostname));
  const relative = path.relative(os.tmpdir(), fs.realpathSync(root));
  assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative));
  assert.equal(fs.readFileSync(path.join(root, '.inline-status-fixture'), 'utf8').trim(), 'fictional-only');
  const tracker = path.join(root, 'data/applications.md');
  const before = fs.readFileSync(tracker, 'utf8');
  const feedback = path.join(root, 'data/opportunity-feedback.jsonl');
  assert.equal(fs.existsSync(feedback), false);
  const row = { title: 'Fixture Junior', company: 'Fictional Example', url: 'https://example.com/job', location: 'Coimbra, Portugal', discovery_pass: true, seniority: { level: 'junior', requirements: [] }, eligibility: { status: 'unknown', evidence: '' }, liveness: { result: 'unverified' }, geography: { matched_places: [], routes: [{ origin: 'Abrantes', destination: 'Coimbra', driving_url: 'https://www.google.com/maps/dir/?api=1&origin=Abrantes&destination=Coimbra&travelmode=driving', transit_url: 'https://www.google.com/maps/dir/?api=1&origin=Abrantes&destination=Coimbra&travelmode=transit' }] } };
  fs.writeFileSync(path.join(root, 'data/opportunity-review.json'), JSON.stringify({ rows: [row, { ...row, url: 'https://example.com/senior', title: 'Fixture Senior', seniority: { level: 'experienced', requirements: [] } }, { ...row, url: 'https://example.com/expired', title: 'Fixture Expired', liveness: { result: 'expired' } }] }));
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_TEST_EXECUTABLE ? { executablePath: process.env.BROWSER_TEST_EXECUTABLE } : {}) });
  t.after(() => browser.close());
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin.origin}/opportunities`);
  await page.getByRole('link', { name: 'Fixture Junior', exact: true }).waitFor();
  assert.equal(await page.locator('article').count(), 1);
  await page.getByRole('checkbox').check();
  assert.equal(await page.locator('article').count(), 3);
  await page.getByRole('checkbox').uncheck();
  await page.getByText('Comparar deslocações por carro ou transportes').click();
  assert.match(await page.getByRole('link', { name: 'Transportes', exact: true }).getAttribute('href'), /travelmode=transit/);
  await page.getByRole('textbox', { name: 'Motivo: Fixture Junior', exact: true }).fill('Quero analisar os requisitos');
  await page.route('**/api/opportunities', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, json: { ok: false } }) : route.continue());
  await page.getByRole('button', { name: 'Interessa', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'A decisão não foi guardada.' }).waitFor();
  assert.equal(await page.getByText(/^Guardado:/).count(), 0);
  assert.equal(fs.existsSync(feedback), false);
  await page.unrouteAll({ behavior: 'wait' });
  await page.getByRole('button', { name: 'Interessa', exact: true }).click();
  await page.getByText('Guardado: Interessa — Quero analisar os requisitos', { exact: true }).waitFor();
  await page.reload();
  await page.getByText('Guardado: Interessa — Quero analisar os requisitos', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Rever mais tarde', exact: true }).click();
  await page.getByText('Guardado: Rever mais tarde — Quero analisar os requisitos', { exact: true }).waitFor();
  assert.equal(fs.readFileSync(feedback, 'utf8').trim().split('\n').length, 2);
  assert.equal(fs.readFileSync(tracker, 'utf8'), before);
  assert.deepEqual(errors, []);
});
